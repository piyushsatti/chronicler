export type MotionId = (typeof MOTION_CATALOG)[number]['id'];

const MOTION_BY_ID: ReadonlyMap<string, MotionEntry> = new Map(
  MOTION_CATALOG.map((entry) => [entry.id, entry]),
);

export function motionEntry(id: MotionId): MotionEntry {
  const entry = MOTION_BY_ID.get(id);
  if (!entry) throw new Error(`Unknown motion catalog id: ${id}`);
  return entry;
}

export const LAUNCH_MOTION_IDS = MOTION_CATALOG.filter((e) => e.launch).map(
  (e) => e.id,
);
