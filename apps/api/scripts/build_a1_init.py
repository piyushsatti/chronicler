HEADER = """-- +goose Up
--
-- A1 squashed init (2026-10-18). Authority: owner-decisions A–M, N1–N8;
-- apps/api/docs/design/graphql-product/migrations.md target inventory.
-- Pointcrawl-only maps (C3). Inbox notifications (D1/N4). No legacy 0003 upgrade path.
--
-- Dual-key convention (API layer):
--   * Internal PK `id` is BIGINT GENERATED BY DEFAULT AS IDENTITY — used for all FKs.
--   * Public `public_id` is UUID NOT NULL UNIQUE DEFAULT gen_random_uuid() for addressable rows.
--
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

"""


def psql(sql: str) -> str:
    cmd = [
        "docker",
        "exec",
        os.environ.get("SQUASH_PG_CONTAINER", "chronicler-squash-pg"),
        "psql",
        "-U",
        "postgres",
        "-d",
        "squash",
        "-At",
        "-c",
        sql,
    ]
    return subprocess.check_output(cmd, text=True)


def pg_dump_schema() -> str:
    cmd = [
        "docker",
        "exec",
        os.environ.get("SQUASH_PG_CONTAINER", "chronicler-squash-pg"),
        "pg_dump",
        "-U",
        "postgres",
        "-d",
        "squash",
        "--schema-only",
        "--no-owner",
        "--no-privileges",
    ]
    return subprocess.check_output(cmd, text=True)


def normalize_public(sql: str) -> str:
    return sql.replace("public.", "").replace("CREATE TABLE public.", "CREATE TABLE ")


def table_from_stmt(stmt: str) -> str | None:
    for pat in (
        r"CREATE TABLE (\w+)",
        r"ALTER TABLE ONLY (\w+)",
        r"ALTER TABLE (\w+)",
        r"CREATE (?:UNIQUE )?INDEX (\w+) ON (\w+)",
        r"CREATE INDEX (\w+) ON (\w+)",
    ):
        m = re.search(pat, stmt)
        if m:
            if pat.startswith("CREATE"):
                return m.group(2)
            return m.group(1)
    return None


def references_dropped_table(stmt: str) -> bool:
    for t in DROP_TABLES:
        if re.search(rf"\b{t}\b", stmt):
            return True
    return False


def references_dropped_column_alter(stmt: str) -> bool:
    for table, col in DROP_COLUMNS:
        if re.search(rf"\b{table}\b", stmt) and re.search(rf"\b{col}\b", stmt):
            return True
    return False


def strip_drop_columns_create(stmt: str, table: str) -> str:
    lines = stmt.splitlines()
    out: list[str] = []
    for line in lines:
        m = re.match(r"\s+(\w+)\s+", line)
        if m and (table, m.group(1)) in DROP_COLUMNS:
            continue
        out.append(line)
    text = "\n".join(out)
    text = re.sub(r",\s*\n\)", "\n)", text)
    return text


def patch_maps_create(stmt: str) -> str:
    stmt = stmt.replace(
        "CONSTRAINT maps_map_kind_check CHECK ((map_kind = ANY (ARRAY['hexgrid'::text, 'pointcrawl'::text])))",
        "CONSTRAINT maps_map_kind_check CHECK ((map_kind = 'pointcrawl'::text))",
    )
    stmt = re.sub(
        r",\n\s+CONSTRAINT maps_hexgrid_shape_check CHECK[^)]+\)\)",
        "",
        stmt,
        count=1,
    )
    for col in ("cols", "rows"):
        stmt = re.sub(rf"\n\s+{col} integer,\n", "\n", stmt)
    return stmt


def split_statements(dump: str) -> list[str]:
    stmts: list[str] = []
    buf: list[str] = []
    dollar_tag: str | None = None
    for line in dump.splitlines(keepends=True):
        if line.startswith("SET ") or line.startswith("SELECT pg_catalog"):
            continue
        if line.startswith("\\"):
            continue
        if "PostgreSQL database dump" in line:
            continue
        if line.startswith("CREATE SCHEMA") or line.startswith("COMMENT ON SCHEMA"):
            continue
        if line.startswith("CREATE EXTENSION"):
            continue
        buf.append(line)
        if dollar_tag is None:
            m = re.search(r"\$([A-Za-z0-9_]*)\$", line)
            if m:
                tag = m.group(1)
                # Count tags on line; odd count opens/closes.
                opens = len(re.findall(rf"\${tag}\$", line))
                if opens % 2 == 1:
                    dollar_tag = tag
        else:
            if re.search(rf"\${dollar_tag}\$", line):
                # Close when tag appears again (pg_dump functions end with $_$;)
                if line.rstrip().endswith(f"${dollar_tag}$;") or line.rstrip().endswith(
                    f"${dollar_tag}$"
                ):
                    dollar_tag = None
        if dollar_tag is not None:
            continue
        if line.rstrip().endswith(";"):
            stmts.append("".join(buf))
            buf = []
    if buf:
        stmts.append("".join(buf))
    return stmts


def add_quest_pointcrawl() -> str:
    return """
CREATE TABLE quest_pointcrawl_nodes (
    quest_id bigint NOT NULL,
    node_id bigint NOT NULL,
    role text NOT NULL,
    CONSTRAINT quest_pointcrawl_nodes_role_check CHECK ((role = ANY (ARRAY['expected'::text, 'visited'::text])))
);

ALTER TABLE ONLY quest_pointcrawl_nodes
    ADD CONSTRAINT quest_pointcrawl_nodes_pkey PRIMARY KEY (quest_id, node_id, role);

ALTER TABLE ONLY quest_pointcrawl_nodes
    ADD CONSTRAINT quest_pointcrawl_nodes_quest_id_fkey FOREIGN KEY (quest_id) REFERENCES quests(id) ON DELETE CASCADE;

ALTER TABLE ONLY quest_pointcrawl_nodes
    ADD CONSTRAINT quest_pointcrawl_nodes_node_id_fkey FOREIGN KEY (node_id) REFERENCES pointcrawl_nodes(id);
"""


def build_migration() -> str:
    dump = normalize_public(pg_dump_schema())
    creates: list[str] = []
    alters: list[str] = []
    indexes: list[str] = []
    functions: list[str] = []
    views: list[str] = []
    triggers: list[str] = []

    for stmt in split_statements(dump):
        s = stmt.strip()
        if not s:
            continue
        if "CREATE TABLE goose_db_version" in s:
            continue
        if references_dropped_table(s):
            continue
        if "CREATE TABLE " in s:
            m = re.search(r"CREATE TABLE (\w+)", s)
            if not m or m.group(1) in DROP_TABLES:
                continue
            table = m.group(1)
            if table in DROP_TABLES:
                continue
            body = strip_drop_columns_create(s, table)
            if table == "maps":
                body = patch_maps_create(body)
            # Keep only CREATE TABLE ... ); block (drop pg_dump header comments).
            body = body[body.index("CREATE TABLE") :]
            creates.append(body)
        elif "ALTER TABLE" in s:
            piece = s[s.index("ALTER TABLE") :]
            if references_dropped_table(piece) or references_dropped_column_alter(piece):
                continue
            alters.append(piece)
        elif "CREATE INDEX" in s or "CREATE UNIQUE INDEX" in s:
            piece = s[s.index("CREATE") :]
            if references_dropped_table(piece) or references_dropped_column_alter(piece):
                continue
            indexes.append(piece)
        elif "CREATE FUNCTION document_readable" in s or "CREATE FUNCTION quest_display_status_at" in s or "CREATE FUNCTION check_product_receipt_complete" in s:
            functions.append(s[s.index("CREATE FUNCTION") :])
        elif "CREATE VIEW quest_display_status" in s:
            views.append(s[s.index("CREATE VIEW") :])
        elif "CONSTRAINT TRIGGER idempotency_product_receipt_check" in s:
            triggers.append(
                "CREATE CONSTRAINT TRIGGER idempotency_product_receipt_check "
                "AFTER INSERT OR UPDATE ON idempotency_keys "
                "DEFERRABLE INITIALLY DEFERRED FOR EACH ROW "
                "EXECUTE FUNCTION check_product_receipt_complete();"
            )

    quest_pc = add_quest_pointcrawl().strip().split("\n\n")
    creates.append(quest_pc[0])
    quest_pc_alters = quest_pc[1:]
    creates.sort(key=lambda x: re.search(r"CREATE TABLE (\w+)", x).group(1))  # type: ignore
    alters.extend(quest_pc_alters)
    # Preserve pg_dump order for constraints (sorting breaks FK/PK ordering).
    indexes.sort()

    body = (
        "\n\n".join(creates)
        + "\n\n"
        + "\n\n".join(alters)
        + "\n\n"
        + "\n\n".join(indexes)
        + "\n\n"
        + "\n\n".join(
            f"-- +goose StatementBegin\n{fn}\n-- +goose StatementEnd" for fn in functions
        )
        + "\n\n"
        + "\n\n".join(triggers)
        + "\n\n"
        + "\n\n".join(views)
    )
    up = HEADER + body.strip() + "\n"

    table_names = sorted({re.search(r"CREATE TABLE (\w+)", c).group(1) for c in creates})  # type: ignore
    down = "\n-- +goose Down\n"
    down += "DROP VIEW IF EXISTS quest_display_status;\n"
    down += "DROP FUNCTION IF EXISTS quest_display_status_at(text,integer,timestamptz,double precision,timestamptz);\n"
    down += "DROP TRIGGER IF EXISTS idempotency_product_receipt_check ON idempotency_keys;\n"
    down += "DROP FUNCTION IF EXISTS check_product_receipt_complete();\n"
    down += "DROP FUNCTION IF EXISTS document_readable(UUID, UUID, TEXT, TEXT, JSONB, UUID, TEXT[], TEXT, BOOLEAN, BOOLEAN, UUID[]);\n"
    for t in reversed(table_names):
        down += f"DROP TABLE IF EXISTS {t} CASCADE;\n"
    down += 'DROP EXTENSION IF EXISTS "pgcrypto";\n'
    return up + down


def column_inventory_from_migration(sql: str) -> dict[str, dict]:
    up = sql.split("-- +goose Down", 1)[0]
    tables: dict[str, dict] = {}
    create_table = re.compile(r"(?s)CREATE TABLE (\w+) \((.*?)\n\);")
    column = re.compile(r"(?m)^    ([a-z][a-z0-9_]*) (.+?)(?:,\s*$|$)")
    for table, block in create_table.findall(up):
        cols = {}
        for name, decl in column.findall(block + "\n"):
            if (table, name) in DROP_COLUMNS:
                continue
            decl = decl.rstrip(",").strip()
            entry = {
                "declaration": decl.upper()
                .replace("TIMESTAMP WITH TIME ZONE", "TIMESTAMPTZ")
                .replace("DOUBLE PRECISION", "DOUBLE PRECISION")
                .replace("INTEGER", "INT")
                .replace("CHARACTER VARYING", "TEXT"),
                "source": "apps/api/db/migrations/0001_init.sql",
                "stage": "squash_a1",
            }
            if "GENERATED ALWAYS AS" in decl.upper():
                entry["generated"] = True
            cols[name] = entry
        tables[table] = {"columns": cols, "baseline_ddl": "\n" + block + "\n"}
    return tables


def main() -> int:
    sql = build_migration()
    MIGRATION_PATH.write_text(sql)
    tables = column_inventory_from_migration(sql)
    col_count = sum(len(t["columns"]) for t in tables.values())
    inv = {
        "baseline_hashes": {
            "apps/api/db/migrations/0001_init.sql": hashlib.sha256(sql.encode()).hexdigest(),
        },
        "change_sha256": hashlib.sha256(json.dumps(tables, sort_keys=True).encode()).hexdigest(),
        "baseline_tables": {},
        "final_tables": tables,
        "squash_note": "A1 single init; 0002-0004 folded",
    }
    INVENTORY_PATH.write_text(json.dumps(inv, indent=2) + "\n")
    print(f"wrote {MIGRATION_PATH} ({len(tables)} tables, {col_count} columns)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
